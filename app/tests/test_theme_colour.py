# (b) Median border colour, and the "excludes the logo" proof
# ---------------------------------------------------------------------------
class TestMedianBorderColour(unittest.TestCase):
    def test_uniform_image_returns_that_colour(self):
        w, h, rgba = tc.decode_png(_fixture_bytes("cc4-dp1-solid-8x6-synthetic.png"))
        r, g, b, a = tc.median_border_colour(w, h, rgba)
        self.assertAlmostEqual(r, 10 / 255.0, places=3)
        self.assertAlmostEqual(g, 140 / 255.0, places=3)
        self.assertAlmostEqual(b, 150 / 255.0, places=3)

    def test_exclusion_box_covering_everything_returns_none(self):
        w, h, rgba = tc.decode_png(_fixture_bytes("cc4-dp1-solid-8x6-synthetic.png"))
        self.assertIsNone(tc.median_border_colour(w, h, rgba, exclude_box=(0, 0, w, h)))

    def test_default_exclude_box_keeps_the_logo_band_out_of_the_scene_fixture(self):
        # cc4-dp1-border-vs-logo-200x120-synthetic.png: everywhere inside
        # default_exclude_box(200, 120) is blue ("logo/carousel"), every-
        # thing else is the true border colour (210, 90, 40).
        data = _fixture_bytes("cc4-dp1-border-vs-logo-200x120-synthetic.png")
        w, h, rgba = tc.decode_png(data)
        box = tc.default_exclude_box(w, h)
        r, g, b, a = tc.median_border_colour(w, h, rgba, exclude_box=box)
        self.assertAlmostEqual(r, 210 / 255.0, places=2)
        self.assertAlmostEqual(g, 90 / 255.0, places=2)
        self.assertAlmostEqual(b, 40 / 255.0, places=2)

    def test_break_it_without_exclusion_the_answer_is_wrong(self):
        """Prove-a-check-by-breaking-it: cc4-dp1-majority-contamination
        has "logo" blue covering the top 60% of rows (which is MORE than
        half of every sampled edge strip, top+left+right combined) and
        true red only in the bottom 40%. Without an exclude_box the
        (correct, robust-to-a-minority-of-noise) median gets outvoted and
        answers blue - proving the exclusion argument is actually load-
        bearing, not a no-op default."""
        data = _fixture_bytes("cc4-dp1-majority-contamination-40x40-synthetic.png")
        w, h, rgba = tc.decode_png(data)
        broken = tc.median_border_colour(w, h, rgba, exclude_box=None, band_frac=0.1)
        fixed = tc.median_border_colour(w, h, rgba, exclude_box=(0, 0, 40, 24), band_frac=0.1)
        self.assertGreater(broken[2], broken[0])   # blue-dominant: B > R
        self.assertGreater(fixed[0], fixed[2])     # red-dominant:  R > B
        self.assertNotEqual(broken, fixed)

    # test_default_exclude_box_matches_the_real_carousel_geometry removed:
    # depended on tests/fixtures/cc4-pistation-x-systemview-reflected-real-
    # capture-2026-09-24.xml, dropped from the public release (see
    # DROPPED-FIXTURES-list.txt).


