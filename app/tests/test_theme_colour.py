# SettleGate - debounce for fast carousel scrolling
# ---------------------------------------------------------------------------
class TestSettleGate(unittest.TestCase):
    def test_fires_once_after_settling(self):
        g = tc.SettleGate(settle_s=0.4)
        g.note("gba", 0.0)
        self.assertIsNone(g.ready(0.39))
        self.assertEqual(g.ready(0.40), "gba")
        self.assertIsNone(g.ready(0.41))            # already consumed

    def test_rapid_scrolling_only_fires_for_the_last_system(self):
        g = tc.SettleGate(settle_s=0.4)
        g.note("gba", 0.0)
        self.assertIsNone(g.ready(0.3))
        g.note("snes", 0.1)                          # scrolled again before settling
        self.assertIsNone(g.ready(0.3))
        g.note("nes", 0.2)                            # and again
        self.assertIsNone(g.ready(0.3))
        self.assertIsNone(g.ready(0.5))               # 0.2 + 0.4 = 0.6, not yet
        self.assertEqual(g.ready(0.6), "nes")          # only the LAST scroll fires
        self.assertIsNone(g.ready(0.65))

    def test_break_it_without_debounce_every_scroll_tick_would_fire(self):
        """A naive "sample on every event" implementation (no gate at all)
        would capture 3 times for 3 scroll ticks; SettleGate must reduce
        that to exactly 1 capture for the settled system."""
        g = tc.SettleGate(settle_s=0.4)
        ticks = [("gba", 0.0), ("snes", 0.05), ("nes", 0.10), ("snes9x", 0.15)]
        naive_capture_count = len(ticks)              # what "no debounce" would cost
        fires = []
        for system, t in ticks:
            g.note(system, t)
            r = g.ready(t)
            if r is not None:
                fires.append(r)
        # nothing fires mid-burst (each note() restarts the window)
        self.assertEqual(fires, [])
        # only after the burst ends and settle_s elapses:
        last_t = ticks[-1][1]
        self.assertEqual(g.ready(last_t + 0.4), "snes9x")
        self.assertEqual(len(fires) + 1, 1)
        self.assertLess(1, naive_capture_count)

    def test_cancel_clears_a_pending_note(self):
        g = tc.SettleGate(settle_s=0.4)
        g.note("gba", 0.0)
        g.cancel()
        self.assertIsNone(g.ready(1.0))


