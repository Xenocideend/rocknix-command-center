class TestColourHelpers(unittest.TestCase):
    def test_hex_to_rgb_6_and_8_digit(self):
        self.assertEqual(tc.hex_to_rgb("ffffff"), (1.0, 1.0, 1.0, 1.0))
        self.assertEqual(tc.hex_to_rgb("000000"), (0.0, 0.0, 0.0, 1.0))
        r, g, b, a = tc.hex_to_rgb("081622")
        self.assertAlmostEqual(r, 8 / 255.0)
        self.assertAlmostEqual(g, 0x16 / 255.0)
        self.assertAlmostEqual(b, 0x22 / 255.0)
        self.assertEqual(a, 1.0)
        _, _, _, a8 = tc.hex_to_rgb("FAFAFFB0")
        self.assertAlmostEqual(a8, 0xB0 / 255.0)

    def test_hex_to_rgb_accepts_leading_hash(self):
        self.assertEqual(tc.hex_to_rgb("#ffffff"), (1.0, 1.0, 1.0, 1.0))

    def test_hex_to_rgb_rejects_garbage(self):
        for bad in (None, "", "zz0000", "12345", "not-a-colour"):
            with self.assertRaises(ValueError):
                tc.hex_to_rgb(bad)

    def test_contrast_text_is_readable_both_directions(self):
        white_text = tc.contrast_text_color((0.05, 0.05, 0.05, 1.0))
        black_text = tc.contrast_text_color((0.95, 0.95, 0.95, 1.0))
        self.assertGreater(tc._luminance(white_text), 0.8)
        self.assertLess(tc._luminance(black_text), 0.2)


