def _encode_png(w, h, pixel_fn):
    """Test-only PNG encoder (colour type 6, RGBA8, filter-none scanlines)
    - the mirror image of theme_colour.decode_png, used only to build
    SYNTHETIC screenshot fixtures. Production code never encodes a PNG."""
    raw = bytearray()
    for y in range(h):
        raw.append(0)
        for x in range(w):
            r, g, b, a = pixel_fn(x, y)
            raw += bytes([r, g, b, a])

    def chunk(ctype, data):
        c = ctype + data
        return struct.pack(">I", len(data)) + c + struct.pack(">I", zlib.crc32(c) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)
    out = tc._PNG_SIG
    out += chunk(b"IHDR", ihdr)
    out += chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    out += chunk(b"IEND", b"")
    return out


