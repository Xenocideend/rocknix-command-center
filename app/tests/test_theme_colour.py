# SampleCache - glue: capture, cache per system, never raise
# ---------------------------------------------------------------------------
class TestSampleCache(unittest.TestCase):
    def _cache_with_fixed_scene(self):
        data = _fixture_bytes("cc4-dp1-border-vs-logo-200x120-synthetic.png")
        return tc.SampleCache(capture=lambda: data)

    def test_capture_caches_per_system(self):
        cache = self._cache_with_fixed_scene()
        self.assertIsNone(cache.cached("gba"))
        result = cache.capture("gba")
        self.assertIsNotNone(result)
        self.assertEqual(cache.captures, 1)
        self.assertEqual(cache.cached("gba"), result)
        self.assertIsNone(cache.cached("snes"))       # a different system: no cross-talk

    def test_capture_failure_returns_none_and_does_not_cache(self):
        cache = tc.SampleCache(capture=lambda: None)
        self.assertIsNone(cache.capture("gba"))
        self.assertIsNone(cache.cached("gba"))
        self.assertEqual(cache.captures, 0)

    def test_decode_failure_returns_none_and_does_not_cache(self):
        cache = tc.SampleCache(capture=lambda: b"not a png")
        self.assertIsNone(cache.capture("gba"))
        self.assertIsNone(cache.cached("gba"))

    def test_forget_clears_one_or_all(self):
        cache = self._cache_with_fixed_scene()
        cache.capture("gba")
        cache.capture("snes")
        cache.forget("gba")
        self.assertIsNone(cache.cached("gba"))
        self.assertIsNotNone(cache.cached("snes"))
        cache.forget()
        self.assertIsNone(cache.cached("snes"))

    def test_uses_the_default_exclude_box_by_default(self):
        # The scene fixture's only "correct" answer (border colour, not
        # the logo blue) is reachable exactly when SampleCache applies
        # default_exclude_box - if it didn't, this would come back blue.
        cache = self._cache_with_fixed_scene()
        bg, fg = cache.capture("gba")
        self.assertGreater(bg[0], bg[2])       # red channel > blue channel


