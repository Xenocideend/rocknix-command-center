# PNG decode (pure Python, no cairo/PIL)
# ---------------------------------------------------------------------------
class TestPngDecode(unittest.TestCase):
    def test_round_trip_solid_colour(self):
        data = _fixture_bytes("cc4-dp1-solid-8x6-synthetic.png")
        w, h, rgba = tc.decode_png(data)
        self.assertEqual((w, h), (8, 6))
        self.assertEqual(len(rgba), 8 * 6 * 4)
        self.assertEqual(tuple(rgba[0:4]), (10, 140, 150, 255))
        self.assertEqual(tuple(rgba[-4:]), (10, 140, 150, 255))

    def test_round_trip_with_filters_sub_up_average_paeth(self):
        # A gradient exercises every byte-to-byte relationship the PNG
        # filters react to (constant rows would only ever pick filter 0).
        def px(x, y):
            return ((x * 7) % 256, (y * 11) % 256, (x + y) % 256, 255)

        data = _encode_png(16, 16, px)
        w, h, rgba = tc.decode_png(data)
        self.assertEqual((w, h), (16, 16))
        for y in (0, 5, 15):
            for x in (0, 5, 15):
                o = (y * w + x) * 4
                self.assertEqual(tuple(rgba[o:o + 4]), px(x, y))

    def test_bad_signature_raises_pngerror_not_a_crash(self):
        with self.assertRaises(tc.PngError):
            tc.decode_png(b"not a png at all")

    def test_truncated_data_raises_pngerror(self):
        data = _fixture_bytes("cc4-dp1-solid-8x6-synthetic.png")
        with self.assertRaises(tc.PngError):
            tc.decode_png(data[:40])

    def test_unsupported_colour_type_raises_pngerror(self):
        # Colour type 3 (palette) is explicitly unsupported.
        ihdr = struct.pack(">IIBBBBB", 1, 1, 8, 3, 0, 0, 0)

        def chunk(ctype, data):
            c = ctype + data
            return struct.pack(">I", len(data)) + c + struct.pack(">I", zlib.crc32(c) & 0xFFFFFFFF)

        data = tc._PNG_SIG + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(b"\x00\x00")) + chunk(b"IEND", b"")
        with self.assertRaises(tc.PngError):
            tc.decode_png(data)


